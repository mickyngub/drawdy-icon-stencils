import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Lucide keeps each icon's categories only in its GitHub repository, not in
// the lucide-static package the palette loads, so they are baked into src/.
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "lucide-categories.ts");
const PRINT_WIDTH = 80;
const LEADING = [
    "layout",
    "arrows",
    "text",
    "shapes",
    "account",
    "devices",
    "files",
    "communication",
    "multimedia",
    "navigation",
    "notifications",
    "charts",
    "design",
    "development",
    "security",
    "connectivity",
    "time",
];

const check = process.argv.includes("--check");
const version = /LUCIDE_VERSION = "([^"]+)"/.exec(readFileSync(join(ROOT, "src", "sources.ts"), "utf8"))?.[1];
if (!version) throw new Error("src/sources.ts has no LUCIDE_VERSION");

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));
const jsonNames = (dir) =>
    readdirSync(dir)
        .filter((file) => file.endsWith(".json"))
        .map((file) => file.slice(0, -".json".length));
const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

async function download(dir) {
    for (const tag of [version, `v${version}`]) {
        const res = await fetch(`https://codeload.github.com/lucide-icons/lucide/tar.gz/refs/tags/${tag}`);
        if (res.status === 404) continue;
        if (!res.ok) throw new Error(`Lucide ${tag}: HTTP ${res.status}`);
        const archive = join(dir, "lucide.tar.gz");
        writeFileSync(archive, Buffer.from(await res.arrayBuffer()));
        execFileSync("tar", ["-xzf", archive, "-C", dir]);
        const top = readdirSync(dir, { withFileTypes: true }).find((entry) => entry.isDirectory());
        if (!top) throw new Error(`Lucide ${tag}: the archive has no folder`);
        return { tag, repo: join(dir, top.name) };
    }
    throw new Error(`Lucide has no tag ${version} or v${version}`);
}

function collect(repo) {
    const categories = new Map();
    for (const id of jsonNames(join(repo, "categories"))) {
        const { title } = readJson(join(repo, "categories", `${id}.json`));
        if (typeof title !== "string") throw new Error(`categories/${id}.json has no title`);
        categories.set(id, { id, title, icons: [] });
    }
    for (const name of jsonNames(join(repo, "icons"))) {
        const { categories: ids } = readJson(join(repo, "icons", `${name}.json`));
        for (const id of new Set(Array.isArray(ids) ? ids : [])) {
            const category = categories.get(id);
            if (!category) throw new Error(`icons/${name}.json names the unknown category ${id}`);
            category.icons.push(name);
        }
    }
    for (const category of categories.values()) category.icons.sort(byCodeUnit);
    return categories;
}

function order(categories) {
    const leading = LEADING.filter((id) => categories.has(id)).map((id) => categories.get(id));
    const rest = [...categories.values()]
        .filter((category) => !LEADING.includes(category.id))
        .sort((a, b) => byCodeUnit(a.title, b.title));
    return [...leading, ...rest];
}

// Written the way Prettier prints it, so formatting the file never breaks --check.
function render(categories) {
    const lines = [
        "// Generated by scripts/lucide-categories.mjs. Do not edit by hand.",
        "export const LUCIDE_CATEGORIES: {",
        "    id: string;",
        "    title: string;",
        "    icons: string[];",
        "}[] = [",
    ];
    for (const { id, title, icons } of categories) {
        lines.push("    {");
        lines.push(`        id: ${JSON.stringify(id)},`);
        lines.push(`        title: ${JSON.stringify(title)},`);
        const quoted = icons.map((icon) => JSON.stringify(icon));
        const inline = `        icons: [${quoted.join(", ")}],`;
        if (inline.length <= PRINT_WIDTH) {
            lines.push(inline);
        } else {
            lines.push("        icons: [");
            for (const icon of quoted) lines.push(`            ${icon},`);
            lines.push("        ],");
        }
        lines.push("    },");
    }
    lines.push("];");
    return `${lines.join("\n")}\n`;
}

const dir = mkdtempSync(join(tmpdir(), "lucide-categories-"));
try {
    const { tag, repo } = await download(dir);
    const categories = collect(repo);
    const ordered = order(categories);
    const content = render(ordered);
    const skipped = LEADING.filter((id) => !categories.has(id));
    if (skipped.length) console.log(`Lucide ${tag} has no category ${skipped.join(", ")}; skipped.`);
    if (check) {
        const committed = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
        if (committed === content) {
            console.log(`✓ src/lucide-categories.ts matches Lucide ${tag} (${ordered.length} categories).`);
        } else {
            console.log(`✗ src/lucide-categories.ts differs from Lucide ${tag}; run npm run lucide-categories.`);
            process.exitCode = 1;
        }
    } else {
        writeFileSync(OUT, content);
        console.log(`Wrote src/lucide-categories.ts: ${ordered.length} categories from Lucide ${tag}.`);
    }
} finally {
    rmSync(dir, { recursive: true, force: true });
}
